function TABLE(head, rows, widths) {
  const cell = (x, i, hdr) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA }, margins: { top: 60, bottom: 60, left: 100, right: 100 },
    borders: { top: border, bottom: border, left: border, right: border },
    shading: hdr ? { type: ShadingType.CLEAR, fill: 'DDE7F3', color: 'auto' } : undefined,
    children: [(x && x.code)
      ? new Paragraph({ alignment: AlignmentType.LEFT, children: [new TextRun({ text: x.t, font: 'Consolas', size: 19 })] })
      : new Paragraph({ bidirectional: true, alignment: AlignmentType.START, children: runs(x, hdr ? { bold: true, size: 20 } : { size: 20 }) })] });
  return new Table({ width: { size: widths.reduce((a, b) => a + b), type: WidthType.DXA }, columnWidths: widths, visuallyRightToLeft: true,
    rows: [new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, i, true)) }),
           ...rows.map(r => new TableRow({ children: r.map((x, i) => cell(x, i, false)) }))] });
}
