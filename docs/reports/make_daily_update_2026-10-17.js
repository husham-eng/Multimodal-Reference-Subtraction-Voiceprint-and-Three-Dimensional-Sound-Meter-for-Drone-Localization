// runs: string, or array of strings / {t, b, code, c}
function runs(x, base = {}) {
  const arr = Array.isArray(x) ? x : [x];
  return arr.map(s => typeof s === 'string'
    ? new TextRun({ text: s, font: FONT, rightToLeft: true, ...base })
    : new TextRun({ text: s.t, bold: s.b, color: s.c, font: s.code ? 'Consolas' : FONT, rightToLeft: !s.code, ...base }));
}
