function IMG(file, wpx, caption) {
  const buf = fs.readFileSync(file);
  const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20);
  return [new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120 }, children: [new ImageRun({ type: 'png', data: buf, transformation: { width: wpx, height: Math.round(wpx * h / w) } })] }),
          P([{ t: caption, b: true, c: '444444' }], { alignment: AlignmentType.CENTER, spacing: { after: 240 } })];
}
